/**
 * World 4 — The Volcanic Vents.
 *
 * The beat sheet is PRD §7.5. The new mechanics are **rising magma** — one-way
 * vertical pressure, the only thing in the game that makes standing still
 * fatal without touching you — and the **Ink Bomb** earned for clearing the
 * Sunken Ship.
 *
 *   A1  x0-27    the vent field. One cracked wall, a three-tile blast radius
 *                and a twenty-frame fuse. Nothing else is in the room, which
 *                is how the player learns to stand clear of their own bomb.
 *   A2  x28-53   the first Magma Snail. It fills the corridor with its
 *                armoured face and the alcove halfway along is the only place
 *                getting behind it is possible.
 *   CP1 x52
 *   B1  x54-91   the first magma rise. Nine shelves, four screens of climb, and
 *                the floor of the world following at a quarter pixel a frame.
 *                No enemies: the magma is the enemy. Pearl 1 is off to the left
 *                of the fourth shelf and costs about three seconds of lead.
 *   B2  x92-129  Cinder Moths over ash bridges. The bridge you planned on may
 *                not be there when you reach it, and the moth that lit it is
 *                long gone — §6.1's "a threat that persists after the enemy".
 *   CP2 x128
 *   C1 x130-163  the scald pools. Ninety frames of superheated water before it
 *                kills, and surfacing bleeds the timer back down, so it is
 *                crossed in stages. Pearl 2 is under a permanent magma pool at
 *                the far end — the first pearl a player is likely to realise
 *                they must come *back* for, and the upgrade is this level's.
 *   C2 x164-185  the snail-and-bomb puzzle. A waist-high wall to open, a shell
 *                to step on, and a moth making the timing worse.
 *   C3 x186-199  the second rise. Eels in the walls, two bomb walls and magma
 *                the whole way up. The fastest ascent in the game.
 *   CP3 x190     the boss door.
 *   BOSS x200-219  the vent chamber. Five vents, one worm, and a floor that
 *                comes up a tile every time you win.
 *
 * **§7.5's pearl ② is not inside a Snail's shell.** A pearl that only exists
 * when a specific enemy dies in a specific place needs a drop system the game
 * does not have, and §12.7 forbids the per-level code that would fake one. It
 * sits behind a second cracked wall in the same corridor instead, which keeps
 * the upgrade that gates it and loses only the flavour. Recorded in the PRD's
 * decisions log.
 *
 * **C2's corridor wall is waist-high rather than floor-to-ceiling.** A full
 * wall there would have made every pearl beyond it "gated on the Ink Bomb" by
 * accident, which turns a real gate into a meaningless one. §7.5 puts the
 * mandatory bomb walls in C3, and that is where they are.
 */

