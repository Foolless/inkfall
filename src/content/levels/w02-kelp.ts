/**
 * World 2 — The Kelp Forest.
 *
 * The beat sheet is PRD §7.3. The world's new mechanic is **currents**, and the
 * player arrives already holding the **Ink Shot** they earned for clearing the
 * Tide Pools — so section A teaches both in the first thirty tiles and never
 * explains either.
 *
 *   A1  x0-29    a flooded shaft with an updraft up its middle, and a kelp knot
 *                at the top that nothing but an Ink Shot opens. The first thing
 *                World 1's reward is good for, four seconds after arriving.
 *   A2  x30-69   the current maze: three chambers with perpendicular flows. A
 *                rightward run, a downdraft to cross under, an updraft out.
 *                Pearl 1 is in the pocket beneath the downdraft — against the
 *                flow, which is the only thing in the room that is.
 *   CP1 x66
 *   B1  x70-101  two Barb Turrets, ten tiles apart, half a cycle out of phase.
 *                Nothing in the room can be killed. That is the lesson.
 *   B2 x102-137  the whipkelp grove: four stalks over a bed of barbs. Shoot the
 *                bases or thread the arcs — both work, and the shooting route
 *                is slower. Pearl 2 is in a sealed pocket over the corridor
 *                whose only door is a knot.
 *   CP2 x131
 *   C1 x138-171  the eel channel: three sockets in a flooded tunnel. Bait,
 *                retreat, pass during the ninety-frame retract. Pearl 3 is
 *                under the floor behind cracked rock and waits for World 3.
 *   C2 x172-199  the bubble ladder, up a strong downdraft. The bubbles pop
 *                after one use, so a mistimed jump means the whole shaft.
 *   C3 x200-217  current, turret and drifters in one ascent.
 *   CP3 x216     the boss door.
 *   BOSS x220-239  the Kelp Warden's shaft — thirty tiles of flooded wall for
 *                four arms to anchor to, and the exit at the top of it.
 *
 * **The grove's pocket is sealed on five sides.** It would have been easier to
 * leave the right-hand wall open and let the knot be decoration, and the
 * reachability solver said so: with the pocket open, taking the pearl proved
 * nothing about holding an Ink Shot. A gate that is not the only way in is not
 * a gate.
 */

