/**
 * World 3 — The Sunken Ship.
 *
 * The beat sheet is PRD §7.4. The new mechanics are **Cling** — earned for
 * clearing the Kelp Forest — and **hazard-as-platform**, which is the single
 * most useful idea this world has: the thing that kills you on contact has a
 * flat top you are meant to stand on.
 *
 *   A1  x0-31    the hull breach. A four-tile chimney and nothing else in the
 *                room. Grip, jump, grip, jump — four storeys, and the first
 *                grip of every airtime is free, so the climb costs no ink.
 *   A2  x32-71   the cargo hold. You come in at the top and the floor is twenty
 *                rows down, so the room is entered by falling into it. Pearl 1
 *                is on that floor: free on the way in, expensive on the way
 *                back, which is §7.4's "descending against progress".
 *   CP1 x69
 *   B1  x72-99   the first Ghost Diver. It comes through the wall, it cannot be
 *                killed, stunned or reasoned with, and the way out is eight
 *                tiles away. There is no fight here at all.
 *   B2 x100-149  the deck. Three Hooklines a third of a cycle apart over a
 *                thirty-tile drop onto broken brass. Their flat tops are the
 *                only footing in the room and the barbs are four pixels under
 *                your feet.
 *   CP2 x147
 *   C1 x150-189  the flood. Five shelves alternating up the room and water
 *                climbing behind you the whole way. Pearl 2 is on the floor of
 *                a drowning room — free on the way in, and gone after that.
 *   C2 x190-217  the brass corridor. Three columns standing in a bed of
 *                fittings, tops level with the ledges either side, and a turret
 *                firing along the height you are crossing at.
 *   C3 x218-229  the powder magazine. Crate lids up the left wall, a crush
 *                clam, and a diver that follows you to the door. Pearl 3 is in
 *                an alcove whose only opening is heat-fused: World 4's problem.
 *   CP3 x225     the boss door.
 *   BOSS x230-249  the wheel room. A tilting floor, a ghost, and a lantern.
 *
 * **The chimney is four tiles wide, not one.** §7.4 A1 says "Cling taught on a
 * single wall", and a single wall cannot be climbed — a wall jump pushes you
 * off it, which is the whole reason it works as an escape. Cling only reads as
 * *traversal* when there is a second face to land on, so the teaching room has
 * two. Recorded in the PRD's decisions log.
 *
 * **Two alcoves had to be sealed on sides nobody would have thought to check.**
 * Pearl 3 was reachable from the boss room next door through a shared ceiling,
 * and then from the corridor above it. Neither would have been found by
 * playing; both were found by asking the solver whether the upgrade actually
 * gated anything.
 */

