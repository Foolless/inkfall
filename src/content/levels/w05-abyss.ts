/**
 * World 5 — The Abyss.
 *
 * The beat sheet is PRD §7.6. Three new things at once: **darkness** (a
 * five-tile light radius, owned by the chapter), **pressure crush**, and
 * **Deep Jet** — the one upgrade found inside a level rather than granted for
 * finishing one.
 *
 *   A1  x0-33    the lightless drop. Seven ledges, six screens of descent, and
 *                nothing in them at all. The scariest room in the game is
 *                empty. Pearl 1 is on a shelf off the side of it.
 *   A2  x34-63   the first Lightless. Only the lure is visible, and it is also
 *                the only thing that can be hit and the only trigger.
 *   CP1 x62
 *   B1  x64-103  the vent chamber. Four vents pouring shrimp against a
 *                three-pip meter, which is arithmetic you lose — the room is
 *                about routing, not fighting. Pearl 2 is behind the last vent
 *                through cracked crust.
 *   B2 x104-129  **Deep Jet.** A nodule on a shelf, alone. Everything after
 *                this is built for four pips.
 *   CP2 x128
 *   C1 x130-159  the pressure room. Three seconds of stillness kills, and the
 *                only footing is three Hooklines over a bed of spines.
 *   C2 x160-192  the Lightless gallery. Five of them, and the only lit path is
 *                the one their own lures make. Pearl 3 is on a one-tile island
 *                twelve rows up in the middle of the room.
 *   C3 x194-209  the final ascent. A current, a cold vent, a wall to cling, a
 *                wall to bomb, a hook to ride — every verb the game has, in the
 *                order it taught them.
 *   CP3 x203     the only conch of the last third.
 *   BOSS x210-229  the Kraken's shelf. Two screens tall, dark, no checkpoint.
 *
 * ## Two findings the solver made, and one claim dropped
 *
 * **Once the player has Cling, vertical distance is not a gate.** Any rock face
 * is a ladder — grip, jump, grip — so a shelf twelve rows above the floor is a
 * shelf anybody can reach if there is a wall anywhere near it. Pearl 3's island
 * is a *single tile* fifteen clear of every face in the room for exactly this
 * reason: the two cells beside it are cling holds, and a three-pip fall carries
 * fourteen tiles. The first two attempts at this pearl were both defeated by
 * ladders nobody would have thought to look for.
 *
 * **A four-pip pearl is the only kind Deep Jet can gate.** Spent-with-Deep-Jet
 * and Full-without are both three pips, so they share an envelope exactly and
 * no geometry can tell them apart. Pearls 1 and 2 are therefore gated by
 * *position* — they lie before the nodule, so a first pass either crosses the
 * world backwards or comes back later — and only pearl 3 is gated by reach.
 *
 * **§7.6's pearl ② is not behind a one-tile crack.** PRD §16 opened the
 * question in Phase 2 and recommended revisiting it "with W5 in front of us".
 * It is, and the answer is unchanged: Full is 12x14 and Spent is 10x10 against
 * 16px tiles, so both fit through a one-tile opening and no small-only passage
 * can be built from geometry. The pearl is behind cracked crust instead. The
 * claim is dropped for v1 rather than worked around; `reach.ts` still derives
 * clearance from the hitbox, so the day those numbers change it starts telling
 * the truth on its own.
 */

