/**
 * World 1 — The Tide Pools.
 *
 * The beat sheet is PRD §7.2, and every room below is one of its beats. The
 * shape is teach, test, complicate: the dash in section A, the dash under
 * pressure in B, the dash combined with everything else in C.
 *
 *   A1  x0-25    a sunlit shelf and one gap you cannot jump. The first lesson
 *                is that jumping is not enough.
 *   A2  x26-53   three ledges four tiles apart. Only an up-dash gets up them,
 *                and pearl 1 sits one more up-dash above the top step.
 *   A3  x54-71   one Snapper on flat ground. The first stomp, and the pip it
 *                gives back.
 *   A4  x72-93   a Snapper on a block where most players take their first hit,
 *                and an Ink Bulb four tiles on, in plain sight.
 *   CP1 x91
 *   B1  x94-129  the tide pool. Swim controls with nothing trying to kill you.
 *                Pearl 2 is in a pocket under the entry shelf, hinted by a
 *                stream of water rising out of nowhere.
 *   B2 x130-157  Drifters over two pits. They cannot be stomped; the only way
 *                past is to spend a pip and go around.
 *   B3 x158-179  a two-tile tunnel with Puffers in it. No room to jump past,
 *                so the only answer is to read the inflate cycle.
 *   CP2 x177
 *   C1 x180-223  collapsing sand over urchins, then the pearl-3 gap: twelve
 *                tiles, which is out of reach until Deep Jet in World 5.
 *   C2 x224-251  three crush clams over nothing. Closed shells are the only
 *                footing.
 *   C3 x252-291  four gaps and a Snapper whose stomp refunds the pip you need.
 *                The level's thesis statement.
 *   CP3 x295     the boss door.
 *
 * **One deliberate deviation.** §7.2 calls A1's gap six tiles. It is authored
 * at five. Six tiles is dx 7, which is exactly the distance feel guarantee 2
 * promises — and that guarantee only holds for a dash taken within six frames
 * of the apex. Asking for frame-perfect apex timing on the first required
 * action in the game is how a player concludes the dash does not work. Five
 * tiles is still flatly unjumpable (a run jump clears four), so the lesson is
 * identical and the execution is not. The 7-tile gap is kept for C3's last
 * jump, by which point the player has spent three minutes learning the timing.
 */

