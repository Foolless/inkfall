/**
 * Nib, hand-authored.
 *
 * One hex digit per pixel, laid out so the squid is visible in a diff:
 *   0 transparent · 1 outline · 2 body · 3 pale
 *
 * Every frame faces **right**. The renderer mirrors for the other facing, which
 * halves the authoring cost and guarantees the two facings can never drift.
 *
 * Charged Nib is not redrawn — it is this exact set under NIB_CHARGED_PALETTE
 * (PRD §9.2: "a recolour of the Full set"). Spent Nib *is* redrawn, at 12x12,
 * because a 16x16 frame scaled down is mush at this resolution.
 */

