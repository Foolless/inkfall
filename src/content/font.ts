/** Anything unmapped draws as this, so a missing glyph is visible, not silent. */
export const MISSING = G('#####', '#...#', '#.#.#', '#...#', '#.#.#', '#...#', '#####')

export function glyph(ch: string): readonly string[] {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? MISSING
}

/** Width in pixels of a string drawn at this size, without trailing tracking. */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * ADVANCE - 1
}
